"""ROS-independent occupancy-grid sensing, planning and motion.

Rows increase along world +y; values are 0 (free), 100 (wall).
Navigation may plan through unknown cells but never sees ground-truth walls.
"""
from collections import deque
import heapq
import math
from pathlib import Path

import numpy as np
import yaml


def load_world(path, resolution=None, start=None):
    path = Path(path).expanduser().resolve()
    config = {}
    if path.suffix.lower() in ('.yaml', '.yml'):
        with path.open() as stream:
            config = yaml.safe_load(stream)
        if not isinstance(config, dict) or 'grid' not in config:
            raise ValueError('YAML must contain a grid matrix')
        grid = np.asarray(config['grid'])
    elif path.suffix.lower() == '.npy':
        grid = np.load(path, allow_pickle=False)
    elif path.suffix.lower() == '.csv':
        grid = np.loadtxt(path, delimiter=',')
    else:
        raise ValueError('Supported matrix formats: .yaml, .yml, .npy, .csv')
    return GridWorld(
        grid, config.get('resolution', 0.2) if resolution is None else resolution,
        config.get('start', [1, 1]) if start is None else start,
        config.get('origin', [0.0, 0.0]), float(config.get('start_yaw', 0.0)),
    )


def line_cells(a, b):
    """Integer Bresenham line including both endpoints."""
    x, y = a
    bx, by = b
    dx, dy = abs(bx - x), -abs(by - y)
    sx, sy = (1 if x < bx else -1), (1 if y < by else -1)
    error = dx + dy
    while True:
        yield x, y
        if (x, y) == b:
            return
        twice = 2 * error
        if twice >= dy:
            error += dy
            x += sx
        if twice <= dx:
            error += dx
            y += sy


class GridWorld:
    def __init__(self, grid, resolution, start, origin=(0.0, 0.0), yaw=0.0):
        grid = np.asarray(grid)
        if grid.ndim != 2 or min(grid.shape) < 3:
            raise ValueError('grid must be a rectangular 2D matrix, at least 3x3')
        if not np.isin(grid, [0, 100]).all():
            raise ValueError('Truth grid accepts only 0 (free) and 100 (occupied); unknown is generated by the sensor')
        if not math.isfinite(float(resolution)) or resolution <= 0:
            raise ValueError('resolution must be finite and positive')
        if len(origin) != 2 or not all(math.isfinite(float(v)) for v in origin):
            raise ValueError('origin must contain two finite coordinates')
        if len(start) != 2 or any(not float(v).is_integer() for v in start):
            raise ValueError('start must contain integer [column, row] cell indices')
        if not math.isfinite(yaw):
            raise ValueError('start_yaw must be finite')
        self.truth = grid.astype(np.int8)
        self.known = np.full(grid.shape, -1, dtype=np.int8)
        self.height, self.width = grid.shape
        self.resolution = float(resolution)
        self.origin = tuple(float(v) for v in origin)
        self.start = tuple(int(v) for v in start)
        if not self.inside(self.start) or self.truth[self.start[1], self.start[0]] != 0:
            raise ValueError('start must be an in-bounds free cell')
        # A solid border bounds all explorers, including legacy RRT sampling code.
        if not (np.all(grid[0] == 100) and np.all(grid[-1] == 100)
                and np.all(grid[:, 0] == 100) and np.all(grid[:, -1] == 100)):
            raise ValueError('Truth grid must have a solid 100-valued outer border')
        self.x, self.y = self.cell_center(self.start)
        self.yaw = yaw
        self.distance = 0.0
        self.collisions = 0
        self.reachable = {self.start}
        queue = deque([self.start])
        while queue:
            for cell in self.neighbors(queue.popleft()):
                if cell not in self.reachable and self.truth[cell[1], cell[0]] == 0:
                    self.reachable.add(cell)
                    queue.append(cell)

    def inside(self, cell):
        return 0 <= cell[0] < self.width and 0 <= cell[1] < self.height

    def cell_center(self, cell):
        return (self.origin[0] + (cell[0] + 0.5) * self.resolution,
                self.origin[1] + (cell[1] + 0.5) * self.resolution)

    def world_cell(self, x, y):
        return (math.floor((x - self.origin[0]) / self.resolution),
                math.floor((y - self.origin[1]) / self.resolution))

    def neighbors(self, cell):
        for dx, dy in ((1, 0), (0, 1), (-1, 0), (0, -1)):
            other = cell[0] + dx, cell[1] + dy
            if self.inside(other):
                yield other

    def observe(self, radius_m):
        center = self.world_cell(self.x, self.y)
        radius = math.ceil(radius_m / self.resolution)
        for y in range(max(0, center[1] - radius), min(self.height, center[1] + radius + 1)):
            for x in range(max(0, center[0] - radius), min(self.width, center[0] + radius + 1)):
                if math.hypot(x - center[0], y - center[1]) * self.resolution > radius_m:
                    continue
                for cx, cy in line_cells(center, (x, y)):
                    self.known[cy, cx] = self.truth[cy, cx]
                    if self.truth[cy, cx] == 100:
                        break

    @property
    def coverage(self):
        return sum(self.known[y, x] == 0 for x, y in self.reachable) / len(self.reachable)

    def costmap(self, inflation_m=0.0):
        result = self.known.copy()
        radius = math.ceil(inflation_m / self.resolution)
        if radius:
            for y, x in np.argwhere(self.known == 100):
                for dy in range(-radius, radius + 1):
                    for dx in range(-radius, radius + 1):
                        if math.hypot(dx, dy) * self.resolution > inflation_m:
                            continue
                        if self.inside((x + dx, y + dy)) and result[y + dy, x + dx] == 0:
                            result[y + dy, x + dx] = 100
        return result

    def plan(self, goal, inflation_m=0.0):
        """Four-connected A* on observed costmap; unknown costs equal free costs."""
        start = self.world_cell(self.x, self.y)
        costs = self.costmap(inflation_m)
        if not self.inside(goal) or costs[goal[1], goal[0]] == 100:
            return None
        queue = [(0, start)]
        parent, distance = {start: None}, {start: 0}
        while queue:
            _, cell = heapq.heappop(queue)
            if cell == goal:
                path = []
                while cell != start:
                    path.append(cell)
                    cell = parent[cell]
                return path[::-1]
            for nxt in self.neighbors(cell):
                if costs[nxt[1], nxt[0]] == 100:
                    continue
                d = distance[cell] + 1
                if d < distance.get(nxt, math.inf):
                    distance[nxt], parent[nxt] = d, cell
                    heuristic = abs(goal[0] - nxt[0]) + abs(goal[1] - nxt[1])
                    heapq.heappush(queue, (d + heuristic, nxt))
        return None

    def move_to(self, x, y):
        """Collision-check the swept point robot, including sub-cell movement."""
        steps = max(1, math.ceil(math.hypot(x - self.x, y - self.y) / (self.resolution / 4)))
        old_x, old_y = self.x, self.y
        for i in range(1, steps + 1):
            nx = old_x + (x - old_x) * i / steps
            ny = old_y + (y - old_y) * i / steps
            cell = self.world_cell(nx, ny)
            if not self.inside(cell) or self.truth[cell[1], cell[0]] == 100:
                self.collisions += 1
                if self.inside(cell):
                    self.known[cell[1], cell[0]] = 100
                return False
            self.distance += math.hypot(nx - self.x, ny - self.y)
            self.x, self.y = nx, ny
        return True
